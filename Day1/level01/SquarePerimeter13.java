import java.util.*;

class SquarePerimeter13 {
	public static void main(String[] args) {

		// Scanner Class
		Scanner sc = new Scanner(System.in);

		// Taking side for calculation
		int side = sc.nextInt();

		// Area of Square
		int areaOfSquare = side * side;

		// Printing area of Triangle
		System.out.println(" The length of the side is " + side + " whose perimeter is " + areaOfSquare);
	}
}