class FindAverageMarks {
	public static void main(String[] args) {

		// Sam's marks of physics, chemistry and maths.
		int physicsMarks = 95, mathsMarks = 94, chemistryMarks = 96;

		// Sam's average Percent.
		int averagePercent = (physicsMarks + mathsMarks + chemistryMarks) / 3;

		// Now we are printing average percent.
		System.out.println("Sam’s average mark in PCM is " + averagePercent);
	}
}