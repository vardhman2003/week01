class FindAge1 {
	public static void main(String[] args) {

		// Harry birth year is 2000 and current year is 2024.
		int birthYear = 2000, currentYear = 2024;

		// Harry current age.
		int currentAge = currentYear - birthYear;

		// Now we are printing current age.
		System.out.println("Harry's age in 2024 is " + currentAge);
	}
}